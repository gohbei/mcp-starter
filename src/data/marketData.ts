// Helper to generate realistic historical candlestick bars for any asset
export function generateCandleSeries(basePrice: number, count = 40): CandleData[] {
  const candles: CandleData[] = [];
  let currentClose = basePrice * 0.94;
  const now = Date.now();
  const dayMs = 24 * 3600 * 1000;

  for (let i = count; i >= 0; i--) {
    const timeStr = new Date(now - i * dayMs).toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
    const volatility = basePrice * 0.015;
    const delta = (Math.random() - 0.47) * volatility;
    const open = currentClose;
    const close = Math.max(open + delta, basePrice * 0.5);
    const high = Math.max(open, close) + Math.random() * volatility * 0.8;
    const low = Math.min(open, close) - Math.random() * volatility * 0.8;
    const volume = Math.floor(Math.random() * 5000000 + 1000000);

    candles.push({
      time: timeStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
    currentClose = close;
  }
  // Ensure the final candle matches basePrice
  candles[candles.length - 1].close = basePrice;
  return candles;
}

